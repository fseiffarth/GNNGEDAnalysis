"""Track planted triangle/square pattern changes along GED edit paths.

Every graph of the synthetic TRIANGLE_SQUARE dataset carries a pendant
pattern on its last nodes: class 0 a triangle on nodes {11, 12, 13}, class 1
a square on nodes {10, 11, 12, 13}. This module walks every edit path through
the intermediate graphs generated by gedpaths
(data/GEDGraphs/F2/<DATASET>_<STRATEGY>/processed/data.pt, one graph per
row_idx of the merged results table), tracks per step whether the source
pattern is still intact and whether the target pattern has been created, and
joins this information onto the merged results table
(results/all_results.csv).

The stored intermediate graphs are used as ground truth instead of replaying
the edit-paths text file because the text file mixes numberings: DELETE
operations reference source-graph node ids while INSERT operations reference
target-graph node ids, and the source->target node mapping is not exported.
All intermediate graphs of a path share the source graph's numbering, so the
edge changed at step k is recovered as the symmetric difference between the
stored graphs of steps k-1 and k (exactly one edge per step; verified).

A pattern counts as intact/complete only while the edges incident to its
nodes are exactly those of the corresponding endpoint graph (the pattern
cycle plus its original attachment edges): any inserted edge touching a
pattern node, a deleted pattern edge, or a deleted attachment edge breaks it.

The target pattern lives in the target graph's numbering; it is mapped into
the path's numbering via a graph isomorphism between the last stored graph of
the path and the target graph.
"""

from __future__ import annotations

